"""Generate spec/pacing_vectors.json - the shared reading-time contract.

The overlay cannot ask the server how long to show a line, because reading speed
and font size are viewer-local. So ``hold_ms`` exists twice, once in Python and
once in JavaScript, and this file is what stops them drifting apart.

Run after changing ``livesubs.segmenter.hold_ms``:

    uv run python tools/gen_pacing_vectors.py

Both ``tests/test_pacing_parity.py`` and ``web/tests/pacing.test.mjs`` check
against the committed file, so a divergence fails a test rather than reaching a
lecture.
"""

from __future__ import annotations

import json
from pathlib import Path

from livesubs.segmenter import hold_ms

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / "spec" / "pacing_vectors.json"

#: Inputs chosen to walk every branch of the formula: the clamp floor, the clamp
#: ceiling, the linear region, zero, a negative, and a non-integer to pin
#: truncation behaviour on both sides.
INPUTS: list[float] = [
    -100,
    -1,
    0,
    1,
    2,
    5,
    6,
    6.7,
    10,
    20,
    33,
    40,
    50,
    58,
    60,
    80,
    100,
    120,
    150,
    200,
    300,
    500,
    1000,
    10000,
]

#: Constants the JavaScript must reproduce. Kept in the vectors file so the two
#: sides cannot disagree about the constants either.
CONSTANTS: dict[str, int] = {
    "BASE_HOLD_MS": 400,
    "PER_CHAR_MS": 55,
    "MIN_HOLD_MS": 700,
    "MAX_HOLD_MS": 6000,
    "MIN_VISIBLE_MS": 800,
}


def build() -> dict:
    return {
        "_comment": (
            "Generated by tools/gen_pacing_vectors.py from "
            "livesubs.segmenter.hold_ms. Do not edit by hand."
        ),
        "constants": CONSTANTS,
        "inputs": INPUTS,
        "expected": [hold_ms(chars) for chars in INPUTS],
    }


def main() -> int:
    payload = build()
    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text(json.dumps(payload, indent=2) + "\n", encoding="utf-8")
    print(f"wrote {TARGET} ({len(INPUTS)} vectors)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
